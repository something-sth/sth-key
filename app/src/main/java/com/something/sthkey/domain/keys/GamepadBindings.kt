package com.something.sthkey.domain.keys

/**
 * 手柄按键的**方位 → evdev 码**映射（单一真源）。
 *
 * ============================================================
 * ⚠️ 为什么不能直接用 evdev 的方位名
 * ============================================================
 * evdev 里四个面键叫 `BTN_NORTH` / `BTN_SOUTH` / `BTN_EAST` / `BTN_WEST`
 * —— 那是**方位**（上/下/右/左），不是 A/B/X/Y。
 *
 * 内核之所以用方位名，正因为"哪个方位叫什么"是**厂商约定**：
 * 同一份内核代码要同时服务 Xbox（上=Y）、任天堂（上=X）、
 * 以及各种用不同布局的国产手柄。
 *
 * ============================================================
 * ⚠️ 这里的两轮对调是**实测**来的，不是抄来的
 * ============================================================
 * evdev 文档与内核 joydev 的"通常"约定是:
 *
 * | 方位 | 通常含义 |
 * |---|---|
 * | `BTN_NORTH`（上） | **Y** |
 * | `BTN_WEST`（左） | **X** |
 * | `BTN_EAST`（右） | **B** |
 * | `BTN_SOUTH`（下） | **A** |
 *
 * 而实测（Flydigi VADER4 与 Microsoft X-Box 360 pad）**四个都不同** ——
 * X/Y 互换、A/B 互换，也就是整体转了 90°。
 *
 * **所以这是一张"按实测校准过的表"**，不是抄文档得来的。
 *
 * ============================================================
 * ⚠️ 改这里之前先读这段
 * ============================================================
 * 这张表是**设备相关**的。如果以后有用户报告"我的也反了"或
 * "我的反而是正的"，正确做法是把它**做成配置项**（按设备或按用户选），
 * 而**不是再翻一次** —— 来回翻会让两边都错，而且没人说得清哪次是对的。
 *
 * 集中在这一个文件里，就是为了让"到底翻过几次"一眼可见。
 */
object GamepadFaceButtons {

    /** 菱形**上**方 */
    const val TOP = KeyCodes.BTN_WEST

    /** 菱形**左**方 */
    const val LEFT = KeyCodes.BTN_NORTH

    /** 菱形**右**方 */
    const val RIGHT = KeyCodes.BTN_SOUTH

    /** 菱形**下**方 */
    const val BOTTOM = KeyCodes.BTN_EAST

    /**
     * 每个方位显示的**键面文字**。
     *
     * ⚠️ 与上面的码**一一对应**：改了码就要一起改文字，
     * 否则会出现"按下亮的是左键，而上面写着 Y"这种错位。
     */
    const val LABEL_TOP = "X"
    const val LABEL_LEFT = "Y"
    const val LABEL_RIGHT = "B"
    const val LABEL_BOTTOM = "A"
}

/**
 * 「标准」样式的三个键。
 *
 * ============================================================
 * ⚠️ 显示的是键鼠的名字，绑的是**手柄**的码
 * ============================================================
 * 这个样式的用途是"用手柄玩键鼠游戏"（例如我的世界基岩版）——
 * 屏幕上写的是玩家脑子里想的键（LMB/RMB/空格），
 * 而实际会亮的是他手上按的手柄键。
 *
 * | 显示 | 绑的手柄键 | 依据（基岩版默认） |
 * |---|---|---|
 * | `LMB` | `BTN_TR`（右扳机 RT） | 攻击 / 放置 |
 * | `RMB` | `BTN_TL`（左扳机 LT） | 使用 / 挖掘 |
 * | `space` | `BTN_SOUTH`（A） | 跳跃 |
 *
 * ⚠️ **第一版我理解错了**：以为"标准"就是"显示键盘键位"，
 * 于是绑了 `BTN_LEFT` / `BTN_RIGHT` / `KEY_SPACE` ——
 * 那三个码在真手柄上**永远不会触发**，表现是"三个键从来不亮"。
 *
 * ⚠️ 这里的 `BTN_SOUTH` 用**码**而不是 [GamepadFaceButtons] 的方位 ——
 * 因为基岩版的跳跃键是**物理 A 键**，而 A 在哪一方位是厂商约定。
 * 实测这台手柄的 A 在 `BTN_EAST`（见上表的对调）。
 */
object GamepadMouseKeys {

    /** 长条键：显示 `space`，实际绑手柄的 A（跳跃） */
    const val SPACE = GamepadFaceButtons.BOTTOM

    /** 左键：显示 `LMB`，实际绑右扳机 RT */
    const val LEFT_MOUSE = KeyCodes.BTN_TR

    /** 右键：显示 `RMB`，实际绑左扳机 LT */
    const val RIGHT_MOUSE = KeyCodes.BTN_TL

    const val LABEL_SPACE = "space"
    const val LABEL_LEFT_MOUSE = "LMB"
    const val LABEL_RIGHT_MOUSE = "RMB"
}
