package com.something.sthkey.domain.config

/**
 * 摇杆（「手柄（标准）」样式里那两个）的**专属外观配置**。
 *
 * ============================================================
 * ⚠️ 为什么要单独一个类，而不是在 [KeyStrokesConfig] 里再加十几个字段
 * ============================================================
 * 摇杆和"按键"不是一回事 —— 按键只有"按下 / 没按下"，
 * 而摇杆有底盘、内圆（摇杆帽）、拇指三层结构，每层各有颜色 / 圆角 /
 * 透明度 / 描边。
 *
 * 混在 `KeyStrokesConfig` 里会有两个问题:
 *
 * 1. 那个类已经很大，再多十几个字段就没人读得完了；
 * 2. **看不出哪些字段是一组的** —— "摇杆帽的圆角"和"Shift 的颜色"
 *    在同一个列表里，改一个要翻半天。
 *
 * 单独一个类之后，"摇杆的设置"一眼可见，而且以后要给摇杆加东西
 * （比如扳机条）也有地方放。
 *
 * ============================================================
 * ⚠️ 全部**只影响显示**，不改变游戏收到的输入
 * ============================================================
 * sthkey 是只读的**指示器** —— 它不把手柄输入发给游戏（游戏自己读手柄）。
 * 所以:
 *
 * | 设置 | 实际作用 |
 * |---|---|
 * | [sizeScale] / [knobScale] | 画多大 |
 * | [color] / [opacity] / [stroke] | 画成什么样 |
 * | [sensitivity] | **输入需要推到多少才画到边**（显示范围） |
 * | [deadZone] | **推一点点就忽略**（显示死区） |
 *
 * [sensitivity] 与 [deadZone] 是"观感"项，用户明确说过
 * "只改变悬浮窗，不改变实际输入"。
 *
 * ⚠️ 所以设置页上要写明这一点 —— 否则会有人以为调了灵敏度就能
 * 改变游戏里的手感，那是**做不到**的（要改游戏收到的值得写 uinput
 * 设备，是另一个量级的工程，也与"显示键位"这个定位不同）。
 */
data class JoystickStyle(

    /**
     * 摇杆的**额外缩放倍数**（在整体缩放之上的又一层）。
     *
     * ```
     * 最终大小 = 布局边长 × 整体缩放(scalePercent) × 本值
     * ```
     *
     * ⚠️ 与 `scalePercent` 是**相乘**关系，不是替代 ——
     * 用户的原话:"摇杆缩放你理解的没错……是整体缩放、摇杆缩放、
     * 摇杆内圆的缩放共同决定的"。
     *
     * ============================================================
     * ⚠️ 上限不是随便定的:它是"两个摇杆刚好贴在一起"
     * ============================================================
     * 用户的原话:"摇杆缩放不应该设置那么大的，最大也只是到了
     * '两个摇杆之间没有间距'的时候，所以最大值要设置好，不能太大"。
     *
     * 两个摇杆分别居中在左右两列，所以要"不重叠"必须满足
     *
     * ```
     * 边长 × sizeScale + 间距 <= 两列中心距
     * sizeScale <= (中心距 − 间距) / 基准边长
     * ```
     *
     * 默认值（边长 125、间距 10、中心距 165）代入得 **1.24** ——
     * 也就是"最多再放大 24%"。
     *
     * ⚠️ 上下限仍然写在这里作为**兜底**，真正的上限由 `KeyLayout`
     * 按当前间距与键宽算出来（间距可调，所以那个上限是变的）。
     * 见 `KeyLayout.keys()` 里的 `stickMaxScale`。
     */
    val sizeScale: Float = 1f,

    /**
     * 底盘方框的圆角比例（`0` = 直角，`0.5` = 正圆）。
     *
     * ⚠️ 相对**边长**的比例，不是绝对像素 —— 这样它在任何缩放下
     * 都是同一个形状。用户之前报过"摇杆变成了一个黑色直角正方形"，
     * 那个 bug 是渲染没分发，不是这个值。
     */
    val cornerRatio: Float = 0.16f,

    /** 底盘填充色的**不透明度**（`0..1`） */
    val opacity: Float = 0.7f,

    /**
     * 底盘填充色（**ARGB，但 alpha 必须是不透明的 `0xFF`**）。
     *
     * ⚠️ 透明度**只由 [opacity] 表达** —— 颜色里不要再藏 alpha，
     * 否则会在配置页被 [com.something.sthkey.ui.component.HexColorRow]
     * 抹掉（那个控件只处理 RGB），表现是"滑到摇杆那一栏摇杆就不见了"。
     * 完整经过见 [Companion] 里那段说明。
     */
    val color: Int = DEFAULT_JOYSTICK_COLOR,

    /**
     * **底盘描边**色（ARGB，alpha 恒为 `0xFF`）。
     *
     * ⚠️ 与 [ringColor] 是**两回事**，别混:
     *
     * | 字段 | 画在哪 |
     * |---|---|
     * | [strokeColor] / [strokeOpacity] / [strokeWidthRatio] | **方框的四条边**（底盘轮廓） |
     * | [ringColor] / [ringOpacity] / [ringWidthRatio] | 底盘上那个**圆**（活动轨道） |
     *
     * 用户的原话:"'摇杆'栏需要加一下描边，你忘记加了，别漏掉颜色
     * 透明度粗细这类的，细心一点"。
     *
     * ⚠️ 我第一版只加了"内圆"那一套（用户管它叫"内接圆边"），
     * 把**底盘本体的描边**整个漏了 —— 而按键样式里也有描边
     * （`config.outline`），摇杆不该少这一项。
     */
    val strokeColor: Int = DEFAULT_STROKE_COLOR,

    /** 底盘描边的不透明度；`0` = 不画 */
    val strokeOpacity: Float = 0f,

    /** 底盘描边的线宽（占边长的比例）；`0` = 不画 */
    val strokeWidthRatio: Float = 0.02f,

    /**
     * 内圆（摇杆帽外面那圈"轨道"）的**描边色**（ARGB）。
     *
     * ⚠️ 名字里带 `Ring` 而不是 `Inner` —— 它画的是**底盘上那个圆**，
     * 不是拇指。用户管它叫"内接圆边"。
     */
    val ringColor: Int = DEFAULT_RING_COLOR,

    /** 内圆圆环的不透明度 */
    val ringOpacity: Float = 0.4f,

    /** 内圆圆环的**线宽**（占边长的比例）；`0` 表示不画 */
    val ringWidthRatio: Float = 0.012f,

    /* ============================================================
     * 摇杆帽（拇指那个圆）
     * ============================================================ */

    /**
     * 摇杆帽的**额外缩放**（在摇杆整体缩放之上的又一层）。
     *
     * ```
     * 最终直径 = 布局拇指直径 × 整体缩放 × 摇杆缩放 × 本值
     * ```
     */
    val knobScale: Float = 1f,

    /** 摇杆帽的颜色（ARGB） */
    val knobColor: Int = DEFAULT_KNOB_COLOR,

    /** 摇杆帽的不透明度 */
    val knobOpacity: Float = 0.9f,

    /**
     * 摇杆帽的圆角比例（`0.5` = 正圆）。
     *
     * ⚠️ 默认 `0.5`。做成可调是为了满足"想要方形摇杆帽"的观感需求 ——
     * 但**方帽在小尺寸下会显得很重**，所以默认仍是圆。
     */
    val knobCornerRatio: Float = 0.5f,

    /** 摇杆帽描边色（ARGB） */
    val knobStrokeColor: Int = DEFAULT_KNOB_STROKE_COLOR,

    /** 摇杆帽描边的不透明度；`0` = 不画描边 */
    val knobStrokeOpacity: Float = 0f,

    /** 摇杆帽描边的线宽（占帽直径的比例） */
    val knobStrokeWidthRatio: Float = 0.08f,

    /* ============================================================
     * 灵敏度 / 死区（**只影响显示**）
     * ============================================================ */

    /**
     * 显示死区（`0..0.5`）。
     *
     * 输入绝对值小于它的部分**不画出来** —— 用来盖掉手柄静止时
     * 那点微小抖动（有些手柄松手后仍有 `±0.02` 的噪声）。
     *
     * ⚠️ 与"灵敏度"分工不同:[deadZone] 管**中心附近**，
     * [sensitivity] 管**整段行程**。
     */
    val deadZone: Float = 0f,

    /**
     * 显示灵敏度（`0.2..3`，`1` = 原样）。
     *
     * 把输入值**乘以**它再钳到 `1` —— 于是:
     *
     * - `> 1`：推到一半就画到边（"更灵敏"）；
     * - `< 1`：推到底也画不到边（"更迟钝"）。
     *
     * ⚠️ **只影响悬浮窗上拇指的位置**，游戏收到的值完全不变。
     */
    val sensitivity: Float = 1f,

    /**
     * 摇杆的**平滑时间**（毫秒）。
     *
     * ============================================================
     * 用户的原话:"这个摇杆'太准了'……就感觉失了一点美感，
     * 参照一下 axon 或者旧项目那个，看能不能写平滑一点"
     * ============================================================
     * 单位是"**追到目标值约 63% 需要多久**"（指数逼近的时间常数）。
     *
     * | 值 | 观感 |
     * |---|---|
     * | `0` | 不平滑，拇指**瞬时跳到**目标位置（数据多准就多准） |
     * | `40..80` | 微微带一点惯性，抖动被抹掉 |
     * | `150+` | 明显拖尾，像"重物"（有人喜欢这种） |
     *
     * ⚠️ **只影响显示**，与 [deadZone] / [sensitivity] 一样 ——
     * 游戏收到的摇杆值完全不变。
     *
     * ============================================================
     * ⚠️⚠️ 实现上有一个坑，别再踩
     * ============================================================
     * 第一版是"每次收到新值就重启一个 150ms 的补间动画"，结果是
     * **一卡一卡的** —— 因为 native 按 `SYN_REPORT` 高频推状态，
     * 两次更新只隔约 16ms，动画**永远只跑完 10% 就被取消**。
     *
     * 正确做法是**一个常驻的帧循环**做指数逼近（见 `Joystick` 里
     * `withFrameNanos` 那段），它**不重启**，所以不会被数据频率影响。
     *
     * 所以:这个值喂给帧循环，**不要**拿去当 `tween` 的时长。
     */
    val smoothingMs: Float = 60f,
) {
    /**
     * 把一个归一化后的摇杆值变成**"该画到哪里"**。
     *
     * ============================================================
     * ⚠️ 这里是**唯一**做死区 / 灵敏度的地方
     * ============================================================
     * 别在 `Joystick` 里再做一遍 —— 两处各做一半的话，
     * 改了一个设置只生效一半，而那种问题极难看出来。
     *
     * 处理顺序（**先死区、后灵敏度**，反过来会得到不同的曲线）:
     *
     * ```
     * 1. 去掉死区:  剩余行程重新映射到 0..1（否则死区会造成"台阶"）
     * 2. 乘灵敏度、钳到 1
     * ```
     *
     * ⚠️ 死区那一步要**重新映射**而不是直接截断:
     * 直接截断的话，跨过死区的那一刻拇指会**跳一下**。
     */
    fun displayValue(raw: Float): Float {
        val magnitude = kotlin.math.abs(raw)
        if (magnitude < 1e-6f) return 0f

        /* ① 死区：把 [deadZone, 1] 这段重新铺满 [0, 1] */
        val dead = deadZone.coerceIn(0f, 0.5f)
        val afterDead = if (dead <= 0f) {
            magnitude
        } else if (magnitude <= dead) {
            return 0f
        } else {
            (magnitude - dead) / (1f - dead)
        }

        /* ② 灵敏度 */
        val scaled = (afterDead * sensitivity.coerceIn(0.2f, 3f)).coerceIn(0f, 1f)

        /* 方向不变，只改长度 */
        return scaled * (raw / magnitude)
    }

    companion object {
        /*
         * ============================================================
         * ⚠️⚠️ 这些颜色**只有 RGB，alpha 必须是 0xFF（不透明）**
         * ============================================================
         * 这里踩过一个很隐蔽的坑，务必看完再改:
         *
         * 颜色编辑控件 `HexColorRow` 是**只处理 RGB 的** ——
         * 它内部 `formatHexDigits()` 里有一句 `and 0xFFFFFF`，
         * 会把 alpha **截掉**。而项目里所有颜色字段
         * （`keyUpColor` / `keyDownColor` …）本来就是纯 RGB，
         * 透明度由**独立的 opacity 字段**管。
         *
         * 第一版这里给了带 alpha 的默认值（`0xB3000000` 半透明黑），
         * 于是:
         *
         * 1. 用户在配置页**滑到"摇杆"那一栏** → `HexColorRow` 进入组合；
         * 2. `LaunchedEffect(value)` 跑 `formatHexDigits(value)`；
         * 3. alpha 被抹成 `00`，随后同步回配置 → 颜色变成 `0x00xxxxxx`；
         * 4. 渲染时 `argbWithOpacity(color, opacity)` = `0 × 1.0` = **全透明**；
         * 5. **摇杆的底盘与内圆直接消失**，而且写进了存档 ——
         *    "除了重新创建一个配置，无法恢复"。
         *
         * ⚠️ 所以:**透明度只由 [opacity] / [ringOpacity] / [knobOpacity]
         * 那三个字段表达**，颜色里不要再藏 alpha。
         * 两者相乘会让"改颜色把摇杆改没了"这种事再发生一次。
         */
        const val DEFAULT_JOYSTICK_COLOR = 0xFF000000.toInt()

        /** 默认内圆圆环色（纯白，透明度看 [ringOpacity]） */
        const val DEFAULT_RING_COLOR = 0xFFFFFFFF.toInt()

        /** 默认摇杆帽色（纯白，透明度看 [knobOpacity]） */
        const val DEFAULT_KNOB_COLOR = 0xFFFFFFFF.toInt()

        /** 默认摇杆帽描边色（纯黑，透明度看 [knobStrokeOpacity]） */
        const val DEFAULT_KNOB_STROKE_COLOR = 0xFF000000.toInt()

        /** 默认底盘描边色（纯白，透明度看 [strokeOpacity]，默认 0 = 不画） */
        const val DEFAULT_STROKE_COLOR = 0xFFFFFFFF.toInt()
    }
}
