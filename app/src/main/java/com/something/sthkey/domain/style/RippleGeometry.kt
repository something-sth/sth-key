package com.something.sthkey.domain.style

/**
 * 「扩散 / 收缩」动画的**几何**——全部是纯函数。
 *
 * ============================================================
 * 为什么单独一个文件、而且不留一点 UI 依赖
 * ============================================================
 * 与 [StickGeometry] 同一个理由:"按住时那个色块该多大"是个纯几何问题，
 * 与 Compose 无关。抽出来就能写测试，而**测试是唯一能在真机之外
 * 验证"形状对不对"的东西**。
 *
 * ============================================================
 * ⚠️⚠️ 为什么重写成"缩放同形状"，而不是"扩散一个圆"
 * ============================================================
 * 用户的原话:"在圆角矩形上（非正方形组件），扩散动画扩散完成时，
 * 扩散出的最终图形，会超出该组件边框，我看上去好像是个矩形，
 * 但是我仔细看了看它的边还有点弯，猜测是因为，扩散动画本身就是
 * 从组件中心生成一个圆然后逐渐扩大"。
 *
 * 他的猜测**完全正确**。旧实现是:
 *
 * ```
 * 覆盖层 = 整个键帽大小的色块
 * 裁剪   = 圆心在键帽中心、半径随进度增长的**圆**
 * ```
 *
 * 那个圆的半径必须取"到最远角的距离"才能在结束时盖满 ——
 * 于是中间过程里，圆的四个弧边**必然伸到圆角矩形之外**:
 *
 * ```
 * ╭────────────╮   圆角矩形（键帽）
 * │  ╭──────╮  │   ← 内切圆:盖不满四角
 * │  │      │  │
 * │  ╰──────╯  │   ← 半径再大一点就超出边框
 * ╰────────────╯
 * ```
 *
 * 它的"边还有点弯"也正是圆的弧。
 *
 * ============================================================
 * 新做法:按比例放大一个**同形状**的小色块
 * ============================================================
 * 用户要的表现（也是他做 iOS 按键显示的朋友的做法:
 * `CGAffineTransformMakeScale(0.1, 0.1)` → 原始大小）:
 *
 * > 在组件中心生成一个与当前组件**相同比例**、但缩放调小的图形，
 * > 然后随动画时间扩大，直到与当前组件重合。
 *
 * 于是 [rippleScale] 给出两个方向的缩放倍数:
 *
 * ```
 * 宽度 = 组件宽 × scaleX
 * 高度 = 组件高 × scaleY
 * ```
 *
 * ⚠️ **为什么宽高各自乘一个倍数，而不是统一乘同一个 `s`**:
 * `s` 同时是"相对大小的直觉"和"两个方向的倍数"，非正方形下二者矛盾:
 *
 * | 取法 | 非正方形下的后果 |
 * |---|---|
 * | `宽 = 组件宽 × s`，`高 = 组件高 × s` | 结束时正好重合，但**过程里比例与组件相同**（正确） |
 * | `边长 = min(宽,高) × s` | 结束时**盖不满**长边 |
 *
 * 这里取第一种:外观比例**全程**与组件一致，结束时精确重合。
 * 代价是细长组件（例如 260×55 的空格）看起来是"横向铺开"而不是
 * "爆炸感"—— 而那正是"与组件同比例"的应有之义。
 *
 * ⚠️ 圆角**也要跟着缩**:色块的形状由 `宽/高/圆角` 三者共同决定。
 * 只缩宽高、圆角保持不变的话，小色块会变成"圆角大到像个胶囊"，
 * 放大过程看起来是"胶囊长成方角"，不是"同一个形状在变大"。
 * 圆角比例由 [rippleCornerRadius] 按同一个倍数缩放。
 */
object RippleGeometry {

    /**
     * 扩散**起点**的相对大小（相对组件本身）。
     *
     * ⚠️ 不取 0:缩放到 0 时宽高都是 0，画不出来（而且某些平台上
     * 0 尺寸的绘制会走异常路径）。取 0.1 与 iOS 那边的
     * `CGAffineTransformMakeScale(0.1, 0.1)` 一致 —— 观感上就是
     * "从一个点炸开"，看不出它其实有 10%。
     */
    const val START_SCALE = 0.1f

    /**
     * 某进度下色块两个方向的缩放倍数。
     *
     * @param progress 动画进度:`0` = 未按下（什么都没有），`1` = 完全按下。
     *   **超出范围会被夹住** —— 补间动画在极端掉帧时可能给出 >1 的值，
     *   那时色块会大于组件本身（又被外层裁掉），看起来是"闪一下"。
     * @return `(scaleX, scaleY)`;`progress <= 0` 时返回 `(0, 0)` 表示不画
     */
    fun rippleScale(progress: Float): Pair<Float, Float> {
        val t = progress.coerceIn(0f, 1f)
        if (t <= 0f) return 0f to 0f
        /* 从 0.1 线性长到 1：`t = 1` 时正好等于组件本身 */
        val s = START_SCALE + (1f - START_SCALE) * t
        return s to s
    }

    /**
     * 色块的圆角（与组件同单位）。
     *
     * ⚠️ 按同一个倍数缩，色块才会"形状不变地长大"（见类注释最后一段）。
     *
     * @param componentRadius 组件自己的圆角
     * @param scale [rippleScale] 给出的倍数（两个方向相同，取其一即可）
     */
    fun rippleCornerRadius(componentRadius: Float, scale: Float): Float =
        (componentRadius * scale).coerceAtLeast(0f)
}
