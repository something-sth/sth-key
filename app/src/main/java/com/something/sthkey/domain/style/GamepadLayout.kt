package com.something.sthkey.domain.style

/**
 * 手柄样式的**布局常量**。
 *
 * ============================================================
 * 为什么单独一个文件
 * ============================================================
 * 两个手柄样式的"长什么样"全在这里，一眼能看全、也能一处调。
 * 渲染代码只消费这些数字，不再自己算 —— 否则"摇杆多大"
 * 会散在四五个地方，改一个忘一个。
 *
 * ============================================================
 * 坐标与单位
 * ============================================================
 * 与按键样式同一个**基础坐标系**（见 [KeyLayout.BASE_WIDTH]）:
 * 单位是"基础像素"，整体缩放由 `KeyStrokesConfig.scalePercent` 乘上去，
 * 本节里的数字**都不感知缩放**。
 *
 * 画布宽度取 600（与按键样式一致）—— 这样"换样式"不会让窗口尺寸突变，
 * 用户看到的是"同一个东西的两种外观"。
 */
object GamepadLayout {

    /**
     * 画布宽度。与 [KeyLayout.BASE_WIDTH] 一致。
     *
     * ⚠️ 用同一个宽度而不是按内容收紧(内容其实只有 232 宽)，理由是
     * **窗口尺寸一致**:用户从键盘样式切到手柄样式时，悬浮窗不该突然小一圈。
     * 内容在画布内**居中**。
     */
    const val BASE_WIDTH = 600f

    /** 一个摇杆的边长 */
    const val STICK_SIZE = 110f

    /** 圆形按键的直径(Y/X/A/B 那一族) */
    const val FACE_BUTTON_SIZE = 56f

    /** 方向键单个键的边长 */
    const val DPAD_BUTTON_SIZE = 44f

    /** 组件之间的通用间距 */
    const val GAP = 12f

    /**
     * 内容外边距。
     *
     * ============================================================
     * ⚠️ 它不是"随便留点空"—— 它决定两个手柄样式的**行高对齐**
     * ============================================================
     * 手柄样式一下面并排两块:
     *
     * ```
     * 左:方向键十字   高 = DPAD × 3 + GAP × 2
     * 右:YXAB 菱形    高 = FACE × 2 + GAP
     * ```
     *
     * 两者本来差 6（132 vs 124）。因为它们在**同一行**里居中，
     * 顶部/底部会各差 3 —— 而那是**一眼能看出来的不齐**。
     *
     * 取 `MARGIN = 26` 之后两边都是 132，正好对齐。
     * 改任何一个按钮尺寸时**必须重新验算**这条。
     */
    const val MARGIN = 26f

    /** 拇指圆的直径 */
    const val THUMB_SIZE = 34f

    /**
     * 摇杆拇指中心的**最大偏移**。
     *
     * ============================================================
     * ⚠️ 这里踩过一个错，值得写清楚
     * ============================================================
     * 第一版照搬了参考实现里"用**外接圆**让拇指能推到方框的角"这句话，
     * 取 `STICK_SIZE / 2 × √2 ≈ 77.8`。
     *
     * **那是错的** —— 它只在"拇指是一个点"时成立。拇指有直径：
     *
     * ```
     * 半边长   = 110 / 2 = 55
     * 拇指半径 = 34 / 2  = 17
     * 拇指不越出方框的条件：最大偏移 + 拇指半径 <= 半边长
     *                      最大偏移 <= 55 - 17 = 38
     * ```
     *
     * 取 77.8 的后果：推到底时拇指边缘到 `77.8 + 22 = 99.8`，
     * 而方框半边长只有 55 —— **拇指整个跑到方框外面**。
     * 用户的描述是"摇杆内的圆居然可以离开摇杆"。
     *
     * ============================================================
     * 那"能推到角"怎么办
     * ============================================================
     * 严格地说，"拇指能到方框的角"与"拇指完整留在方框内"**不可兼得** ——
     * 前者要求偏移 `55√2`，后者要求偏移 `<= 38`。只能二选一。
     *
     * **选后者**（完整留在框内），理由：
     *
     * - 拇指跑出框是**明显的视觉 bug**，用户一眼就看出来；
     * - 而"斜推时差一点到角"几乎没人会注意 —— 因为斜推时的偏移是
     *   `38 × (1 + (√2 - 1) × blend)`，在方形混合区仍然比线性映射
     *   **多走 41%**，"外圈更远"的手感是保住了的。
     *
     * 也就是说：**保留方形映射的手感，但把上限夹到几何上安全的值**。
     */
    const val STICK_TRAVEL_RADIUS = STICK_SIZE / 2f - THUMB_SIZE / 2f


    /**
     * 摇杆底盘圆的直径（画在方框内的那个圆）。
     *
     * ⚠️ 它必须 >= `2 × (最大偏移 + 拇指半径)`，否则拇指会**越过这条轨道**
     * 跑到圆外面去 —— 那也是"圆离开摇杆"的一个成因。
     *
     * 现在：`2 × (38 + 17) = 110`，正好等于方框边长 ——
     * 也就是说"拇指贴到方框边"时刚好也贴到底盘圆。
     */
    const val STICK_BASE_CIRCLE = 2f * (STICK_TRAVEL_RADIUS + THUMB_SIZE / 2f)

    /**
     * "标准"样式里长条键(空格)与 LMB/RMB 的高度。
     *
     * ⚠️ 用户原话是"宽不要太大" —— 这里取 `40`,与方向的单键同高,
     * 既不显得笨重，又够放一个清晰的标签。
     */
    const val BAR_HEIGHT = 40f

    /**
     * "标准"样式里长条键的宽度。
     *
     * ============================================================
     * ⚠️ 它必须**由摇杆尺寸推出来**，不能写死
     * ============================================================
     * 用户的要求是"长是两个摇杆边长的和再加上那一点点间隙":
     *
     * ```
     * 长条键宽 = 摇杆边长 × 2 + 间隙
     * ```
     *
     * 写死一个数的话，以后改 [STICK_SIZE] 或 [GAP] 就会出现
     * "长条键与上面两个摇杆对不齐" —— 而那是一眼能看出来的丑。
     */
    const val BAR_WIDTH = STICK_SIZE * 2 + GAP

    /** LMB / RMB 的宽度:与单个摇杆同宽(用户的要求) */
    const val MOUSE_KEY_WIDTH = STICK_SIZE

    /** 方向键十字的总高:`上 + 间隙 + 中间一行 + 间隙 + 下` */
    const val DPAD_CROSS_HEIGHT = DPAD_BUTTON_SIZE * 3 + GAP * 2

    /** YXAB 菱形的总高:`上 + 间隙 + 中间一行 + 间隙 + 下` */
    const val FACE_DIAMOND_HEIGHT = FACE_BUTTON_SIZE * 2 + GAP
}

/**
 * 两个手柄样式的**内容高度**。
 *
 * ============================================================
 * ⚠️ 为什么单独放一个对象、而不是让样式注册表自己算
 * ============================================================
 * 窗口尺寸按样式注册表给的 `baseSize` 算，而内容是渲染层**实际画出来**的。
 * 两处各算一遍的必然结果是"改了一处忘了另一处" ——
 * 表现是内容被裁掉、或者底部留一片空白。
 *
 * 所以高度**只在这里定义一次**，样式注册表直接引用:
 *
 * ```
 * OverlayBaseSize(GamepadLayout.BASE_WIDTH, GamepadHeights.ONE)
 * ```
 *
 * ⚠️ 渲染层（`Gamepad1Content` / `Gamepad2Content`）的布局必须与
 * 这里的推导**保持一致** —— 改布局时两边一起看。
 */
object GamepadHeights {

    /**
     * 手柄样式一:摇杆行 + 十字/菱形行。
     *
     * ⚠️ 第二行取**十字**的高度（`DPAD × 3 + GAP × 2`）而不是菱形 ——
     * 十字更高，而两列是等高的（见 [GamepadLayout.MARGIN] 的验算）。
     * 取错那个会让窗口比内容矮 8 像素，底边被裁。
     */
    val ONE: Float =
        GamepadLayout.MARGIN +
            GamepadLayout.STICK_SIZE +
            GamepadLayout.GAP +
            GamepadLayout.MARGIN +
            GamepadLayout.DPAD_CROSS_HEIGHT +
            GamepadLayout.MARGIN

    /** 手柄样式二:两个方形摇杆 + 长条键 + LMB/RMB */
    val TWO: Float =
        GamepadLayout.MARGIN +
            GamepadLayout.STICK_SIZE +
            GamepadLayout.GAP + GamepadLayout.BAR_HEIGHT +
            GamepadLayout.GAP + GamepadLayout.BAR_HEIGHT +
            GamepadLayout.MARGIN
}
