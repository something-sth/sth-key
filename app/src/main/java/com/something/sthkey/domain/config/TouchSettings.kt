package com.something.sthkey.domain.config

import com.something.sthkey.domain.custom.JoystickFollowMode

/**
 * **触屏**样式专有的设置。
 *
 * ============================================================
 * 为什么单独一块（与 [Live2DSettings] / `CustomLayoutSettings` 同一个思路）
 * ============================================================
 * 触屏与手柄**只是长得像**（都是两个摇杆 + 长条键），运行原理完全不同:
 *
 * | | 手柄 | 触屏 |
 * |---|---|---|
 * | 输入来自 | 物理手柄的轴（evdev `EV_ABS`） | 用户在**屏幕上**划出来的触摸 |
 * | 摇杆中心 | 手柄自己上报的中位 | **触摸区域的中心**（固定，不是按下点） |
 * | 位置从哪来 | 手柄的 ADC 值 | `(触点 - 区域中心) / 区域半径` |
 *
 * ⚠️ 所以它的设置不能塞进 [KeyStrokesConfig.joystick]（那是手柄摇杆的观感）——
 * 塞进去的话，改触屏的手感会连带把用手柄时的观感也改掉。
 *
 * ============================================================
 * ⚠️ 外观**共用**、手感**各一套**（用户明确的取舍）
 * ============================================================
 * 用户的原话:
 *
 * > 触屏我也打算做专门摇杆组件，跟之前做键盘鼠标摇杆的逻辑相同，
 * > **UI 用同一套**，**摇杆手感之类的设置单独做**
 *
 * | | 取自哪里 |
 * |---|---|
 * | 可见外观（颜色 / 圆角 / 描边） | [KeyStrokesConfig.joystick]（就是手柄那份 `JoystickStyle`） |
 * | **缩放** | **本类**，两个摇杆各一个（移动轮盘通常比视角摇杆小） |
 * | **手感（死区 / 灵敏度 / 平滑）** | **本类**，两个摇杆各一套 |
 *
 * ⚠️ 外观**故意不各存一份**:用户要的是"UI 用同一套"——
 * 在触屏里调颜色应该和在手柄里调颜色是同一件事。
 *
 * ⚠️⚠️ **我第一版给这条写的理由是错的**（记下来免得再犯）:
 * 当时写的是"不共用的话，用户在触屏里调了颜色、切到手柄会变回去"。
 * 用户当场指出:
 *
 * > 触屏和手柄是不同样式，**不能切换**，哪来切到手柄这一说？
 *
 * ⚠️ 他说得对 —— 样式创建后不能切换（见 `ConfigListScreen` 里那句
 * "不同样式的配置互不通用，创建后不能切换样式"），那个场景**不存在**。
 * 我拿一个不可能发生的场景替自己的设计辩护。
 *
 * ⚠️ 真理由是**只有一份真源**:外观是"这个摇杆长什么样"，
 * 而触屏与手柄画的是同一类东西，分两份就会出现
 * "两个地方调同一件事、结果还不一样"——那是漂移的温床。
 * 结论没变（外观共用是对的），但**理由必须是这个**。
 */
data class TouchSettings(
    /**
     * 移动轮盘（左，手柄左摇杆的位置）。
     *
     * ⚠️ **不是**一个 `JoystickComponent` —— 那个类带 `x/y/width/height`，
     * 而触屏两个摇杆的位置是**跟着布局走的**（与手柄同一套算法）。
     * 存一份坐标会出现两个真源:改 `scalePercent` 时布局会重算，
     * 而存在这里的那份不会 —— 于是"摇杆跑到别处去了"。
     * 位置归布局，这里只存**这个摇杆自己的东西**。
     */
    val move: TouchStickSettings = TouchStickSettings(sizeScale = 1f),

    /**
     * 视角摇杆（右，手柄右摇杆的位置）。
     *
     * ⚠️ 它的**输入**与移动轮盘完全不同:没有区域，
     * 吃的是"所有没落在任何触摸区域里的滑动" —— 像一块触摸板。
     */
    val camera: TouchStickSettings = TouchStickSettings(
        /*
         * ⚠️ 默认缩放与移动轮盘**相同**（都是 1）。
         *
         * ⚠️ 我第一版给的是 `0.8`（比移动轮盘小），理由是"视角摇杆常常要
         * 更灵敏"。**那是错的**:灵敏度是 [TouchStickFeel.sensitivity]
         * 的事，与"画多大"没有任何关系 —— 我把两件不相干的事混在了一起。
         *
         * ⚠️ 用户实测后指出:"触屏配置的视角摇杆比移动摇杆小一点，
         * 要解决一下，**两个摇杆大小应该统一**"。
         *
         * ⚠️ 所以默认值统一，要改大小由用户自己在两个摇杆上分别调。
         */
        sizeScale = 1f,
        feel = TouchStickFeel(
            /*
             * ⚠️ 而**手感**的默认值确实与移动轮盘不同:手指短促地划一下
             * 就要转视角，所以死区更小、更灵敏。
             *
             * ⚠️ 而且它是"触摸板"式的**累加**（见类注释里的输入说明），
             * 没有"推到边缘"这个动作 —— 灵敏度直接是增量倍率。
             */
            deadZone = 0f,
            sensitivity = 2.5f,
            smoothingMs = 40f,
        ),
    ),

    /**
     * 全部**触摸区域**:哪一块屏幕算"操作某个东西"。
     *
     * ============================================================
     * ⚠️ 不只有移动轮盘，**每个显示的按键都可以有一块**（用户要求）
     * ============================================================
     * 用户的原话:
     *
     * > 你只搞了一个「轮盘」触摸区域，但是实际上**不止轮盘需要配置，
     * > 其他按键同样需要**，参考 axon
     *
     * ⚠️ Axon 那边就是"四个固定区域:摇杆 + LMB + RMB + SPACE"——
     * 每个区域对应一个能按的东西。这里做成**一个列表**，
     * 槽位 id 复用 `KeyLayout.Id`（与键位映射同一套 id）。
     *
     * | 区域绑的槽位 | 作用 |
     * |---|---|
     * | [JOYSTICK_SLOT_ID]（虚拟槽位） | 区域内按下 → 算**偏移向量**给移动轮盘 |
     * | `A_BUTTON` / `LMB` / `RMB` / `SHOULDER_L` / `SHOULDER_R` | 区域内按下 → **那个键就按下**，松手抬起 |
     *
     * ⚠️ **空列表表示"用户还没配过"** ——
     * 打开悬浮窗时要靠它判断该不该弹「没有配置触摸区域」的提示。
     *
     * ⚠️ 视角摇杆**没有**区域:按设计，没被任何区域覆盖的地方
     * 天然就是它的检测范围（用户原话:"本身没有悬浮窗的位置
     * 就是视角摇杆的检测位置"）。
     */
    val regions: List<TouchRegionBinding> = emptyList(),
) {
    /**
     * **真正生效**的区域（用户配过的那些）。
     *
     * ⚠️ 判定与渲染都必须用这个，**不能用 [regions]** ——
     * 列表里可能含有"编辑器画出来给用户拖、但用户没碰过"的占位条目，
     * 那些**不该生效**（详见 [TouchRegionBinding.pinned]）。
     */
    val activeRegions: List<TouchRegionBinding>
        get() = regions.filter { it.pinned }

    companion object {
        /**
         * 移动轮盘那个区域的**虚拟槽位 id**。
         *
         * ⚠️ 它不是 `KeyLayout.Id` 里任何一个 —— 摇杆在布局里占一个
         * `KeyBox`（好参与尺寸计算），但它**不绑键码**，
         * 所以不能拿它的槽位 id 当"按键"用（那会让渲染层去点灯）。
         *
         * ⚠️ 用一个不可能与真实槽位撞车的名字（真实 id 都是大写下划线）。
         */
        const val JOYSTICK_SLOT_ID = "@move"
    }
}

/**
 * **一块触摸区域**绑定到某个槽位。
 *
 * ============================================================
 * ⚠️ 中心是**整屏归一化**，边长是**较短边归一化**（两者单位不同！）
 * ============================================================
 * | 字段 | 单位 | 范围 |
 * |---|---|---|
 * | [centerX] | 整屏宽的比例 | `0..1`（横竖**各自**） |
 * | [centerY] | 整屏高的比例 | `0..1` |
 * | [size] | **较短边**的比例 | 见 [TouchRegionSpec] |
 *
 * ⚠️⚠️ **为什么中心不用较短边**（我第一版用了，是个 bug）:
 * 用较短边的话，中心能取到的横向范围只有"一个短边" ——
 * 横屏时短边是高度，于是**区域横向只能放到屏幕一半的地方**。
 *
 * 用户实测后指出:
 *
 * > 你怎么把轮盘触摸区域限制在屏幕一半位置了，这是多此一举的操作，
 * > 你考虑过**左撇子**吗？要是有人习惯**右手摇杆**呢
 *
 * ⚠️ 他说得对:那正好把右半屏排除掉了，右手摇杆的人根本放不过去。
 * 中心改成整屏归一化之后，屏幕**任何位置**都能放。
 *
 * ⚠️ 而**边长仍然按较短边** —— 那是为了正方形**不随朝向变形**:
 * 按宽算的话横屏下同一块区域会被拉成一条细缝（见 [TouchRegionSpec]）。
 * 两者单位不同是**刻意的**，换算在 `TouchInput` 里做。
 */
data class TouchRegionBinding(
    /**
     * 绑到哪个槽位。
     *
     * ⚠️ 取值是 `KeyLayout.Id` 里的字符串，或者 [TouchSettings.JOYSTICK_SLOT_ID]。
     * ⚠️ 用一个**不存在**的槽位 id 是允许的（手改 JSON）——
     * 那时这块区域谁都不绑，等于不存在（不崩）。
     */
    val slotId: String,
    /** 中心 X，整屏宽的比例 `0..1` */
    val centerX: Float,
    /** 中心 Y，整屏高的比例 `0..1` */
    val centerY: Float,
    /** 边长，占屏幕**较短边**的比例 */
    val size: Float,
    /**
     * 这块区域是用户**真的配过**的吗（拖动过或拉过滑块）。
     *
     * ============================================================
     * ⚠️⚠️ 为什么要存这个（"持久化漏洞"的根因）
     * ============================================================
     * 编辑器一打开会给**所有**槽位各画一个方块（用户选的方案 ①），
     * 而"哪些该写进配置"原来靠编辑器服务内存里的一个 `touched` 标记。
     *
     * ⚠️ 那个标记**不持久化**，于是:
     *
     * | 做法 | 后果 |
     * |---|---|
     * | 不写未动过的 | 用户**看不到**哪些区域真的生效了（配置里没有，界面上也没说） |
     * | 全写 | 用户没碰过的 A / LT / RT **凭空有了区域**；而且 `regions` 不再为空 → **"没配区域"的提示再也不弹** |
     *
     * ⚠️ 两种都不对。根因是**数据模型里缺"这块是我真配过的"这个概念** ——
     * 补上它之后:
     *
     * | 值 | 含义 |
     * |---|---|
     * | `true` | 用户配过 → **生效**，且会被写进存档 |
     * | `false` | 只是"打开编辑器时画出来给你拖的" → **不生效**，也不写进存档 |
     *
     * ⚠️ 判定"要不要生效"时用 `pinned` 过滤，而不是"在不在列表里" ——
     * 列表可能同时含有两种（配过的 + 这次新画的）。
     */
    val pinned: Boolean = false,
)

/**
 * **一个**触屏摇杆自己的设置。
 *
 * ⚠️ 分成两块（[sizeScale] 与 [feel]）而不是摊平在 [TouchSettings] 里:
 * 两个摇杆各有一份，摊平就得写 `moveSizeScale` / `cameraSizeScale`
 * 这种成对的字段 —— 加第三项时又要加一对，很容易漏一边。
 */
data class TouchStickSettings(
    /**
     * 相对"手柄同位置槽位"的缩放。
     *
     * ⚠️ 与手柄的 `JoystickStyle.sizeScale` **不是同一个东西**:
     * 那个是"手柄摇杆在这个槽位里画多大"，这个是"触屏这个摇杆
     * 相对同一槽位画多大"。分开存是为了让触屏能独立调大小，
     * 而不影响用户用手柄时的观感。
     */
    val sizeScale: Float = 1f,

    /** 这个摇杆的手感 */
    val feel: TouchStickFeel = TouchStickFeel(),
)

/**
 * 一块触摸区域的**几何**（正方形）。
 *
 * ============================================================
 * ⚠️ 只考虑边长（用户明确要求）
 * ============================================================
 * 用户的原话:
 *
 * > 触摸区域只用考虑**边长**就行了，至少大多数游戏内组件都不会
 * > 设立成长方形吧
 *
 * ⚠️ 所以这里**只有 `size`，没有宽高两个值**。
 *
 * ============================================================
 * ⚠️⚠️ 单位:中心是**整屏归一化**，边长是**较短边归一化**
 * ============================================================
 * | 字段 | 单位 | 范围 |
 * |---|---|---|
 * | [centerX] | 整屏**宽**的比例 | `0..1` |
 * | [centerY] | 整屏**高**的比例 | `0..1` |
 * | [size] | 屏幕**较短边**的比例 | 见 [TouchRegionSpec] |
 *
 * ⚠️ 两者单位**不同**是刻意的，理由相反:
 *
 * | | 用整屏 | 用较短边 |
 * |---|---|---|
 * | 中心 | ✅ **能放到屏幕任何位置** | ❌ 横向只能用到"一个短边"——横屏下就是**屏幕一半**，右手摇杆的人放不过去 |
 * | 边长 | ❌ 横屏下正方形被拉成一条**细缝** | ✅ 任何朝向下**看起来一样大** |
 *
 * ⚠️⚠️ 我第一版**两者都用较短边**，于是中心横向被限制在屏幕一半 ——
 * 用户实测指出:
 *
 * > 你怎么把轮盘触摸区域限制在屏幕一半位置了，这是多此一举的操作，
 * > 你考虑过**左撇子**吗？要是有人习惯**右手摇杆**呢
 *
 * ⚠️ 换算在 `TouchInput` 里做（见 `toShortEdge` 的说明）。
 *
 * ============================================================
 * ⚠️ 与悬浮窗坐标是两套，故意不重合（用户确认过）
 * ============================================================
 * 触摸区域回答的是"哪个组件读哪片屏幕的触摸"，悬浮窗回答的是"画在哪"。
 * 两者不需要重合，只需要**能在界面上对照**（编辑时会画出方块定位）。
 *
 * ⚠️ 用中心 + 边长而不是左上角 + 边长:
 * 摇杆的**中心**是"手指不按时帽子该在哪"，而那个点必须与区域中心一致。
 * 存左上角的话每次算向量都要先加半个边长，多一次心算就多一次错的机会。
 */
data class TouchRegion(
    /** 中心 X，整屏**宽**的比例 `0..1` */
    val centerX: Float,
    /** 中心 Y，整屏**高**的比例 `0..1` */
    val centerY: Float,
    /** 边长（占屏幕**较短边**的比例，见 [TouchRegionSpec]） */
    val size: Float,
)

/**
 * 触摸区域的取值范围与默认值。
 *
 * ⚠️ 这些常量放在 `domain`（而不是编辑界面里）:
 * 采集层与编辑界面都要用同一个范围，散着写迟早漂
 * （摇杆描边上限那件事就是这么来的）。
 */
object TouchRegionSpec {

    /**
     * 边长占**较短边**的比例。
     *
     * ⚠️ 用"较短边"而不是"宽"或"高":
     * 手机横屏时高度才是短边、竖屏时宽度是短边 —— 按短边算，
     * 同一个比例在两种朝向下**看起来一样大**。
     * 按宽算的话横屏下区域会被拉成一条细缝。
     */
    const val SIZE_MIN = 0.10f
    const val SIZE_MAX = 0.60f
    const val SIZE_DEFAULT = 0.30f

    /**
     * 中心的合法范围。
     *
     * ⚠️ **就是整整一个屏幕**（`0..1`，横竖各自）——
     * 不许收窄，那正是"限制在屏幕一半"那个 bug 的来源。
     *
     * ⚠️ 允许区域**部分露出屏幕**（中心贴边时）:
     * 编辑器的窗口带 `FLAG_LAYOUT_NO_LIMITS`，露出去的部分照样画得出来、
     * 照样能拖回来。而**完全**跑出屏幕是不可能的（中心被夹在 `0..1`）。
     */
    const val CENTER_MIN = 0f
    const val CENTER_MAX = 1f

    /** 移动轮盘的默认区域:左下角（右撇子拇指自然停放的位置） */
    val MOVE_DEFAULT = TouchRegion(centerX = 0.25f, centerY = 0.72f, size = SIZE_DEFAULT)

    /**
     * 一个按键区域的默认中心。
     *
     * ⚠️ **不在屏幕上真画一个方块**（那会挡住游戏画面），
     * 而是给一个"从右下角开始阶梯排开"的起点 ——
     * 用户把方块拖到想要的位置即可。
     *
     * ⚠️ 用阶梯而不是同一个点:全叠在一起的话用户拖开一个才发现
     * 下面还压着四个，而他不知道有几个。
     */
    fun defaultCenterFor(index: Int): Pair<Float, Float> {
        val column = index % 3
        val row = index / 3
        return (0.78f - column * 0.22f) to (0.30f + row * 0.22f)
    }

    /** 把一块区域夹回合法范围 */
    fun clamp(region: TouchRegion): TouchRegion = TouchRegion(
        centerX = region.centerX.coerceIn(CENTER_MIN, CENTER_MAX),
        centerY = region.centerY.coerceIn(CENTER_MIN, CENTER_MAX),
        size = region.size.coerceIn(SIZE_MIN, SIZE_MAX),
    )

    /** 把一块绑定夹回合法范围（顺手夹住它的几何） */
    fun clamp(binding: TouchRegionBinding): TouchRegionBinding {
        val geometry = clamp(
            TouchRegion(binding.centerX, binding.centerY, binding.size),
        )
        return binding.copy(
            centerX = geometry.centerX,
            centerY = geometry.centerY,
            size = geometry.size,
        )
    }
}

/**
 * 触屏摇杆的**手感** —— 死区 / 灵敏度 / 平滑。
 *
 * ============================================================
 * ⚠️ 与手柄摇杆的死区/灵敏度**不是同一套**
 * ============================================================
 * 手柄那套是"把 ADC 值映射到 -1..1"用的；触屏的输入已经是归一化坐标，
 * 所以这三项在这边含义不同:
 *
 * | 项 | 含义 |
 * |---|---|
 * | [deadZone] | 离中心多近算"没动"（防手抖） |
 * | [sensitivity] | 移动轮盘:推多远算满偏；视角摇杆:增量倍率 |
 * | [smoothingMs] | 平滑时间；`0` = 不平滑 |
 *
 * ⚠️ 不做成"复用手柄那三项"的原因:两者的**基准**不一样。
 * 手柄的灵敏度是相对 ADC 满量程的，触屏的是相对**区域半径**的 ——
 * 混用会出现"手柄调好的值，切到触屏完全不能用"。
 */
data class TouchStickFeel(
    /**
     * 死区:归一化偏移小于它就当作 0。
     *
     * ⚠️ 与手柄一样是**圆形**死区（比较向量长度），不是分别比 x/y ——
     * 分别比的话斜向会漏（`(0.09, 0.09)` 每个分量都没超，但实际推得挺远）。
     */
    val deadZone: Float = 0.08f,

    /**
     * 灵敏度倍数。
     *
     * | 用在哪 | 含义 |
     * |---|---|
     * | 移动轮盘 | `偏移 / 区域半径 × 灵敏度`；`1.0` = 推到边缘刚好满偏 |
     * | 视角摇杆 | 帧间增量的倍率（见采集层） |
     */
    val sensitivity: Float = 1.0f,

    /** 平滑时间（毫秒）；`0` = 不平滑（原样跟随） */
    val smoothingMs: Float = 60f,

    /**
     * 摇杆帽的**跟随方式**（两种，用户可切换）。
     *
     * ============================================================
     * ⚠️ 与「摇杆-键盘」的 `KeyboardJoystickFeel.mode` **同一个枚举、同一套语义**
     * ============================================================
     * 用户的原话:
     *
     * > 自定义 key 里的触屏摇杆也**需要有精准和平滑切换**吧，
     * > 你这个不是都在触屏样式做过了吗
     *
     * ⚠️ 他说得对 —— 而且我原来的做法**用错了参数**:
     * `linearDurationMsOf` 把 [smoothingMs] 当"线性跟随时长"用，
     * 而那是**弹簧的平滑时间**（"弹簧有多软"），不是"走完这段距离要多久"。
     *
     * ⚠️ 症状就是用户报的"**一卡一卡**":
     * native 只在 `SYN_REPORT` 时输出一帧，所以喂数据的间隔**由触摸屏
     * 决定、而且不均匀**。`smoothingMs = 60` 短于那个间隔 →
     * 线性动画走完之后**停在那儿等下一帧** → 一顿一顿。
     *
     * ⚠️ 现在两个模式各有各的参数（见 [durationMs]），与键盘摇杆一致:
     *
     * | 模式 | 参数 | 含义 |
     * |---|---|---|
     * | [JoystickFollowMode.SMOOTH] 平滑 | [smoothingMs]「平滑时间」 | 弹簧有多软 |
     * | [JoystickFollowMode.REGULAR] 常规 | [durationMs]「响应时间」 | 走完这段距离的时长 |
     *
     * ⚠️ **默认 [JoystickFollowMode.SMOOTH]** —— 那是**触屏样式原来的行为**，
     * 老配置（那时候还没有这个字段）读出来必须与升级前一模一样。
     */
    val mode: JoystickFollowMode = JoystickFollowMode.SMOOTH,

    /**
     * **常规模式**下"从中心走到满偏"要多久（毫秒）。
     *
     * ⚠️ 与 [smoothingMs] 是**两个模式里同一件事**的参数，界面上位置相同、
     * 只在切模式时换（与键盘摇杆逐字同一个约定）。
     *
     * ⚠️ 默认 `120f`:与键盘摇杆的默认值一致。它要**盖过喂数据的一帧间隔**
     * （触摸屏的 `SYN_REPORT` 间隔，通常 30~120ms）——
     * 太短就会出现"走完停在原地等下一帧"的**一顿一顿**，
     * 那正是这个字段存在的意义。
     */
    val durationMs: Float = 120f,
)

/** 触屏手感的范围（编辑界面与夹取共用，真源在这里） */
object TouchFeelSpec {
    const val DEAD_ZONE_MIN = 0f
    const val DEAD_ZONE_MAX = 0.4f

    const val SENSITIVITY_MIN = 0.2f
    const val SENSITIVITY_MAX = 4f

    const val SMOOTHING_MIN = 0f
    const val SMOOTHING_MAX = 300f

    /** 摇杆相对槽位的缩放范围 */
    const val SIZE_SCALE_MIN = 0.3f
    const val SIZE_SCALE_MAX = 1.5f

    fun clamp(feel: TouchStickFeel): TouchStickFeel = TouchStickFeel(
        deadZone = feel.deadZone.coerceIn(DEAD_ZONE_MIN, DEAD_ZONE_MAX),
        sensitivity = feel.sensitivity.coerceIn(SENSITIVITY_MIN, SENSITIVITY_MAX),
        smoothingMs = feel.smoothingMs.coerceIn(SMOOTHING_MIN, SMOOTHING_MAX),
    )

    fun clampScale(scale: Float): Float = scale.coerceIn(SIZE_SCALE_MIN, SIZE_SCALE_MAX)
}
