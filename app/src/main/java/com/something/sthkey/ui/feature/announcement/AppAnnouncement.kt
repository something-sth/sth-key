 * **旧条目不要删**：弹窗里可以翻页看历史，用户忘了上一版改了什么时能查。
 *
 * 正文用"小节 + 若干行"的朴素结构，而不是一整段富文本：
 * 弹窗空间有限，分行才扫得动；链接单独成行、整行可点（见 AnnouncementDialog），
