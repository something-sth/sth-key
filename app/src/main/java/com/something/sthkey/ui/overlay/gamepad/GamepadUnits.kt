package com.something.sthkey.ui.overlay.gamepad

/**
 * 手柄渲染的**单位换算**。
 *
 * ============================================================
 * ⚠️ 三个坐标空间，混用会得到很隐蔽的错
 * ============================================================
 * | 空间 | 单位 | 谁在用 |
 * |---|---|---|
 * | 布局常量 | **基础像素** | `GamepadLayout`、`StickGeometry` 的返回值 |
 * | Compose 尺寸 | dp | `Modifier.size((x * scale).dp)` |
 * | `DrawScope` 坐标 | **像素** | `Canvas { }` 里的 `size` / `Offset` |
 *
 * 关系:
 *
 * ```
 * 基础像素 × scale = dp
 * dp × 密度        = 像素
 * ```
 *
 * 所以：
 *
 * ```
 * 像素 / 基础像素 = scale × 密度
 * ```
 *
 * ============================================================
 * ⚠️⚠️ 这里错过一次，而且错得很隐蔽
 * ============================================================
 * 第一版写成 `1f / scale`。它**看起来**有道理 ——
 * `OverlayContent` 里那个 `factor` 就是 `pxToDpFactor`（= `1/密度`），
 * 于是 `scale = 1/密度 × uiScale`，而 `1/scale` 就"像是"密度 × 缩放。
 *
 * **但不是。** 关键在**画布实际有多大**:
 * `Modifier.size((sizeDp * scale).dp)` 让 Compose 把它排成
 * `sizeDp × scale` dp，也就是 `sizeDp × scale × 密度` **屏幕像素**。
 * 而画布里的绘制坐标用的是**基础像素** ——
 * 所以要除的是"一个基础像素等于几个屏幕像素" = `scale × 密度`。
 *
 * 用 `1/scale` 的后果:绘制尺寸变成 `基础 × 密度 × scale²`，
 * **多乘了一个 `密度 × scale`**。而 `scale` 里含 `1/密度`，
 * 于是这一项随用户的缩放百分比**反向变化**:
 *
 * | 用户调整整体缩放 | `scale` | 错误公式的放大倍数 | 现象 |
 * |---|---|---|---|
 * | 调小 | 变小 | **变大** | 圆与描边**反而变大**，还跑出底盘 |
 * | 调大 | 变大 | 变小 | 圆与描边**反而变小** |
 *
 * 用户的原话是"摇杆里面的白色圆圈和内接圆边，会随着整体缩放变小而变大，
 * 变大而变小" —— 一字不差。
 *
 * ⚠️ 所以这个函数**必须拿到密度**。不要试图用 `scale` 反推 ——
 * 那正是错的来源。
 */
internal fun baseToPixelFactor(scale: Float, density: Float): Float =
    scale * density.coerceAtLeast(0.01f)
