package com.something.sthkey.ui.overlay

/**
 * 行距系数的下限（**矢量与图片字体共用**）。
 *
 * ============================================================
 * 为什么需要一个下限
 * ============================================================
 * 用户可以把"行间距"往负方向调（收紧），但**不能调到 0** ——
 * 那样两行会直接重叠在一起，看起来像渲染坏了，而不是"紧凑"。
 * 留 0.5 倍行高：已经相当紧凑，又不会重叠。
 *
 * ============================================================
 * ⚠️ 为什么单独放一个文件
 * ============================================================
 * Kotlin 的**包级 `private` 常量不能同名** —— 同一个包下两个文件
 * 各声明一个 `private const val X` 会直接编译失败。
 *
 * 而"行距下限"这个值三条绘制路径（`KeyGrid`、`CustomKeyGrid`、
 * `BitmapFontText`）**都要用**，所以只能有一个声明点。
 *
 * ⚠️ 必须**共用一个值**：否则同一个"行间距"滑块在矢量字体与图片字体下
 * 能收到的下限不一样，用户会以为是哪一个坏了。
 */
internal const val MIN_LINE_SPACING_FACTOR = 0.5f
