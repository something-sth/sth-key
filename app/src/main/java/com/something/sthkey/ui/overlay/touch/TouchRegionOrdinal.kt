package com.something.sthkey.ui.overlay.touch

/**
 * 区域在列表里的**显示序号**：① .. ⑳，超过 20 用普通数字。
 *
 * ============================================================
 * ⚠️ 为什么要有它（用户反馈）
 * ============================================================
 * 用户配了几块区域、都绑同一个按键时，标题会一模一样
 * （`按键区域 (按键 · A)` × 3），在面板里**分不出哪行是哪块**。
 *
 * 试过的两个方向:
 *
 * | 方案 | 问题 |
 * |---|---|
 * | 名字染成方块颜色 | 浅紫灰底上蓝/绿/橙/青的对比度只有 ~2:1，11sp 很难读;而且调色板只有 6 个，第 7 块开始颜色重复 |
 * | **加序号** | 没有上述问题，还可以无限排;色弱用户也能用 |
 *
 * ⚠️ 所以序号是**主标识**，颜色只做辅助（面板行的小圆点）。
 *
 * ⚠️ 序号按**当前列表顺序**排，删掉一块后后面的会重排 ——
 * 但面板与屏幕方块**同时**重排，任何一刻"第几行 ↔ 第几块"都是对的。
 * 要"永久不变"就得给 `CustomTouchRegion` 加持久化字段并改编解码，
 * 那是另一档成本，暂不做。
 *
 * ⚠️ 数字是**独立绘制**的，不拼进区域标题:
 * 标题在方块上会被截断（`…(按键 · A)`），拼进去序号就会跟着被切掉。
 *
 * @param index 从 **0** 开始的列表下标
 */
fun touchRegionOrdinal(index: Int): String {
    val number = index + 1
    return if (number in 1..CIRCLED.size) CIRCLED[number - 1] else number.toString()
}

/**
 * ① .. ⑳。
 *
 * ⚠️ 只到 20:再往后没有统一的带圈字形（㉑ 的字体支持很不稳定），
 * 而且真配到 20 块以上的用户极少 —— 超过就退回普通数字，仍然能读。
 */
private val CIRCLED = listOf(
    "①", "②", "③", "④", "⑤", "⑥", "⑦", "⑧", "⑨", "⑩",
    "⑪", "⑫", "⑬", "⑭", "⑮", "⑯", "⑰", "⑱", "⑲", "⑳",
)
