package com.something.sthkey.capture

/**
 * 手柄的**模拟量**状态。
 *
 * ============================================================
 * 与 [InputEvent] 的关系：一个事件 vs 一份状态
 * ============================================================
 * 采集层在 [InputEvent] 上收到的是**单个轴的一条变化**
 * （"左摇杆 X 现在是多少"），而显示层要的是**一台手柄的整体姿态**
 * （"左摇杆指向哪里"）。这个类就是后者。
 *
 * 分开的理由和鼠标位移那里一样：消费方按帧取用，而事件可能来得极碎
 * （摇杆每秒几十上百次上报）。在采集层合成一份状态，
 * 消费方就不用自己拼。
 *
 * ============================================================
 * ⚠️ 所有值都是**归一化**过的 `-1f .. 1f`
 * ============================================================
 * 设备细节（ADC 位数、轴能力查询、中点校准、死区）全部在
 * **原生 monitor** 里处理完了（见 `GamepadNativeProtocol` 的类注释）。
 * 到这里只剩"摇杆推到了哪里"。
 *
 * ============================================================
 * ⚠️ 坐标系：X 向右为正，**Y 向下为正**（屏幕坐标）
 * ============================================================
 * 这是**屏幕的约定**，不是摇杆的物理约定 —— 而它由数据源决定:
 * 原生 monitor 输出的 `ly` / `ry` 已经把 evdev 的"上为正"
 * 翻成了"下为正"。
 *
 *
 * ```kotlin
 * val ty = cy + y * travel     // ← 加号，不是减号
 * ```
 *
 * ⚠️ **这里踩过坑**:第一版本文件写的是"Y 向上为正"，
 * 渲染层于是按那个约定取了反 —— 结果**两个摇杆的 Y 都反了**
 * （往上推、拇指往下走）。
 *
 * 所以:渲染层**直接加** `ly` / `ry`，不要取反。
 */
data class StickState(
    /** 左摇杆 X，右为正 */
    val lx: Float = 0f,

    /** 左摇杆 Y，**下为正**（屏幕坐标） */
    val ly: Float = 0f,

    /** 右摇杆 X，右为正 */
    val rx: Float = 0f,

    /** 右摇杆 Y，**下为正**（屏幕坐标） */
    val ry: Float = 0f,

    /**
     * 方向键的 X（**只有轴报法的手柄有值**）。
     *
     * 通常是 `-1f / 0f / 1f` 三个离散值，不像摇杆那样连续。
     *
     * ⚠️ 另一批手柄把方向键报成独立的按键（`BTN_DPAD_UP` 等），
     * 那种情况下这里是 0，方向键的状态在 [CaptureSession.pressedKeys] 里。
     * **两条路都要支持**，见 `KeyCodes` 里 `BTN_DPAD_*` 的说明。
     *
     * ⚠️ 现在走的是**按键那条路** —— native 输出的位掩码第 20..23 位
     * 就是方向键，所以 `hat*` 这两个字段**目前没有数据源**。
     * 保留它们是为了以后接"轴报法"输入源时不用改数据模型。
     */
    val hatX: Float = 0f,

    /** 方向键的 Y，**下为正**（与摇杆一致） */
    val hatY: Float = 0f,
) {
    /** 左摇杆有没有被推动 */
    val leftActive: Boolean get() = lx != 0f || ly != 0f

    /** 右摇杆有没有被推动 */
    val rightActive: Boolean get() = rx != 0f || ry != 0f

    /**
     * 左摇杆的**长度**（`0f .. 1f`）。
     *
     * ⚠️ 用 `min(1f, 长度)` 而不是直接 `sqrt`:斜推到底时
     * `lx` 与 `ly` 都接近 1，长度会到 `1.414` —— 不夹住的话
     * "推到底"的量会被算成 141%。
     */
    val leftMagnitude: Float
        get() = kotlin.math.min(1f, kotlin.math.hypot(lx, ly))

    /** 右摇杆的长度，同样夹到 1 */
    val rightMagnitude: Float
        get() = kotlin.math.min(1f, kotlin.math.hypot(rx, ry))
}
